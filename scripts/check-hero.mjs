import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:5173');
  await page.evaluate(() => document.fonts.ready);
  await page.waitForSelector('.hero-formation.is-ready');
  await page.clock.install();
  await page.locator('#formation-replay').click();
  await page.evaluate(() => document.getAnimations().filter(animation => animation.effect?.target?.closest('.hero-copy')).forEach(animation => animation.finish()));
  await page.clock.runFor(2200);
  assert.equal(await page.locator('.hero-formation').getAttribute('data-phase'), '0');
  await page.screenshot({ path: '.impeccable/review/hero-sequence-start.png' });
  await page.clock.runFor(9000);
  assert.equal(await page.locator('.hero-formation').getAttribute('data-phase'), '2');
  await page.screenshot({ path: '.impeccable/review/hero-sequence-assembly.png' });
  await page.clock.runFor(8500);
  assert.equal(await page.locator('.hero-formation').getAttribute('data-phase'), '3');
  await page.screenshot({ path: '.impeccable/review/hero-sequence-final.png' });
  const finished = await page.locator('canvas').evaluate(canvas => canvas.toDataURL());
  await page.clock.runFor(4000);
  assert.ok(await page.locator('canvas').evaluate(canvas => canvas.toDataURL()) === finished, 'Finished animation holds still');
  await page.locator('#formation-replay').click();
  assert.equal(await page.locator('.hero-formation').getAttribute('data-phase'), '0');
  await page.clock.runFor(4000);
  await page.evaluate(() => scrollTo({ top: document.querySelector('#contact').offsetTop, behavior: 'instant' }));
  await page.clock.runFor(200);
  await new Promise(resolve => setTimeout(resolve, 100));
  const paused = await page.locator('canvas').evaluate(canvas => canvas.toDataURL());
  await page.clock.runFor(4000);
  assert.ok(await page.locator('canvas').evaluate(canvas => canvas.toDataURL()) === paused, 'Offscreen animation pauses');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await new Promise(resolve => setTimeout(resolve, 100));
  await page.clock.runFor(100);
  assert.equal(await page.locator('#formation-replay').isDisabled(), true);
  assert.equal(await page.locator('.hero-formation').getAttribute('data-phase'), '3');
  await page.setViewportSize({ width: 390, height: 1050 });
  await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
  await page.clock.runFor(100);
  await page.screenshot({ path: '.impeccable/review/hero-sequence-mobile.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('PASS 19-second sequence, assembly and final states, replay, still finish, offscreen pause, reduced motion and mobile layout');
} finally { await browser.close(); }
